#ITERATIVE USING FOR LOOP

a = ["Hulk", "Thor", "Ironman", "Captain America"]
for i in a:
    print(i)
    
    
    ## ITERATION USING FOR LOOP WITH RANGE AND LENGTH FUNCTION
    for j in range(len(a)):
        print(a[j])
        
        
        ### Iteration USING WHILE LOOP
        i = 0
        while i<len(a):
            print(a[i])
            i+=1
            
